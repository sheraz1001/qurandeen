// Get all duas for a specific category
export function getAllAzkaar(categoryId) {
  return duasData[categoryId] || [];
}

// Get a specific dua by ID
export function getDuaById(categoryId, duaId) {
  const duas = duasData[categoryId] || [];
  return duas.find(d => d.id === duaId);
}

// Search duas across all categories
export function searchDuas(query) {
  const results = [];
  const normalizedQuery = query.toLowerCase();
  
  Object.entries(duasData).forEach(([categoryId, duas]) => {
    const category = azkaarCategories.find(c => c.id === categoryId);
    duas.forEach(dua => {
      if (
        dua.arabic.includes(query) ||
        (dua.translation && dua.translation.toLowerCase().includes(normalizedQuery)) ||
        (dua.transliteration && dua.transliteration.toLowerCase().includes(normalizedQuery))
      ) {
        results.push({ ...dua, categoryId, categoryName: category?.nameEn });
      }
    });
  });
  
  return results;
}

